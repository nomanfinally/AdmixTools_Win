"""Compressed input and optional graph rendering, against a pinned Linux run.

Run --bin DIR --output DIR on each OS, optionally --render; then --compare L W.
No extra Python packages. Raw output and generated bytes are retained.
"""
import argparse
import gzip
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

import parity


def digest(data):
    return hashlib.sha256(data).hexdigest()


def normalized(data, binary_dir):
    text = parity.normalize(data, str(binary_dir))
    # Only the generated temporary pathname and command operand quotation differ.
    command = re.search(r'^unzip cmd: gunzip -c ("[^"]+"|\S+) > ("[^"]+"|\S+)$', text, re.M)
    if command:
        temporary = command[2].strip('"')
        text = text.replace(temporary, '<GENOTMP>')
        text = re.sub(r'^unzip cmd: gunzip -c ("[^"]+"|\S+) > "?<GENOTMP>"?$',
                      lambda m: 'unzip cmd: gunzip -c ' + m[1].strip('"') + ' > <GENOTMP>', text, flags=re.M)
    return text


def run(binary_dir, output, render):
    output.mkdir(parents=True, exist_ok=False)
    work = output / 'working directory with spaces'
    parity.fixtures(work)
    (work / 'tmp').mkdir()
    env = dict(os.environ, OPENBLAS_NUM_THREADS='1', OMP_NUM_THREADS='1',
               OPENBLAS_CORETYPE='NEHALEM', LC_ALL='C', STMP='tmp')
    env['PATH'] = str(binary_dir) + os.pathsep + env.get('PATH', '')
    manifest = {'binary_dir': str(binary_dir), 'platform': sys.platform, 'render': render, 'cases': {}, 'files': {}}

    def invoke(name, tool, arguments, expected=0, selected_env=None):
        executable = binary_dir / (tool + ('.exe' if os.name == 'nt' else ''))
        completed = subprocess.run([executable.name, *arguments], executable=str(executable),
                                   cwd=work, env=selected_env or env, capture_output=True, timeout=90)
        for stream in ('stdout', 'stderr'):
            (output / f'{name}.{stream}').write_bytes(getattr(completed, stream))
        manifest['cases'][name] = {'returncode': completed.returncode, 'arguments': arguments}
        assert (completed.returncode == expected) if expected is not None else (completed.returncode != 0), name
        # Pristine upstream leaves packed/EIGENSTRAT gzip temporary files behind.
        # Remove only this run's named file after verifying its exact bytes.
        if os.name != 'nt':
            match = re.search(rb'^unzip cmd: gunzip -c (\S+) > (/var/tmp/genotmp:[0-9]+)$', completed.stdout, re.M)
            if match:
                temporary = Path(os.fsdecode(match[2]))
                if temporary.is_file():
                    assert temporary.read_bytes() == gzip.decompress((work / os.fsdecode(match[1])).read_bytes())
                    temporary.unlink()
        print(f'{name}: {completed.returncode}', flush=True)
        return completed

    def save_file(name):
        data = (work / name).read_bytes()
        (output / name).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(work / name, output / name)
        manifest['files'][name] = digest(data)
        return data

    # Produce packed and transposed inputs using the native upstream utilities.
    invoke('prepare-packed', 'convertf', ['-p', 'par.convertf'])
    invoke('prepare-transpose', 'transpose', ['output.geno', 'input.tgeno'])
    rows = (work / 'input.geno').read_text().splitlines()
    individuals = [line.split()[0] for line in (work / 'input.ind').read_text().splitlines()]
    (work / 'input.ancestry').write_text(''.join(
        f'rs{snp:05d} {individual} {rows[snp][index]}\n'
        for snp in range(len(rows)) for index, individual in enumerate(individuals)), newline='\n')
    result_lines = []
    for kind, source in [('text', 'input.geno'), ('packed', 'output.geno'),
                         ('transpose', 'input.tgeno'), ('ancestry', 'input.ancestry')]:
        payload = (work / source).read_bytes()
        # Concatenated members exercise gzip boundaries independently of rows.
        boundary = len(payload) // 2 + 1
        compressed = gzip.compress(payload[:boundary], mtime=0) + gzip.compress(payload[boundary:], mtime=0)
        (work / f'{kind}.gz').write_bytes(compressed)
        par = (work / 'par.qpDstat').read_text().replace('input.geno', f'{kind}.gz')
        (work / f'par.{kind}').write_text(par, newline='\n')
        completed = invoke(f'gzip-{kind}', 'qpDstat', ['-p', f'par.{kind}'])
        result_lines.append([line for line in completed.stdout.splitlines() if line.startswith(b'result:')])
        # A conversion also verifies generated genotype bytes, not only statistics.
        par = (work / 'par.convertf').read_text().replace('input.geno', f'{kind}.gz')
        par = par.replace('output.geno', f'{kind}.geno').replace('output.snp', f'{kind}.snp').replace('output.ind', f'{kind}.ind')
        (work / f'par.convert-{kind}').write_text(par, newline='\n')
        invoke(f'convert-{kind}', 'convertf', ['-p', f'par.convert-{kind}'])
        for suffix in ('geno', 'snp', 'ind'):
            assert save_file(f'{kind}.{suffix}') == (work / f'output.{suffix}').read_bytes(), (kind, suffix)
        assert (work / f'{kind}.gz').read_bytes() == compressed
        if os.name == 'nt':
            assert not list((work / 'tmp').glob('genotmp.*')), kind
    assert result_lines[0] and all(lines == result_lines[0] for lines in result_lines)
    manifest['gzip_results_identical'] = True
    if os.name == 'nt':
        # Reject failed decompression before the genotype readers see partial data.
        good = gzip.compress((work / 'input.geno').read_bytes(), mtime=0)
        bad_crc = bytearray(good)
        bad_crc[-8] ^= 1
        for kind, payload in [('crc', bytes(bad_crc)), ('truncated', good[:-8]),
                              ('plain', b'not a gzip stream'), ('empty', b'')]:
            (work / f'bad-{kind}.gz').write_bytes(payload)
            (work / 'par.bad').write_text((work / 'par.qpDstat').read_text().replace('input.geno', f'bad-{kind}.gz'))
            completed = invoke(f'invalid-{kind}', 'qpDstat', ['-p', 'par.bad'], expected=None)
            assert b'result:' not in completed.stdout
            assert not list((work / 'tmp').glob('genotmp.*'))
            assert (work / f'bad-{kind}.gz').read_bytes() == payload
        # Windows argument quoting must survive spaces and shell metacharacters.
        unusual = 'input & sample file.gz'
        (work / unusual).write_bytes(good)
        (work / 'par.spaces').write_text((work / 'par.qpDstat').read_text().replace('input.geno', f'"{unusual}"'))
        completed = invoke('gzip-spaces', 'qpDstat', ['-p', 'par.spaces'])
        assert [line for line in completed.stdout.splitlines() if line.startswith(b'result:')] == result_lines[0]
        assert not list((work / 'tmp').glob('genotmp.*'))
    if render:
        gs = next((shutil.which(name) for name in ('gswin64c', 'gswin32c', 'gs') if shutil.which(name)), None)
        assert gs, 'native Ghostscript is required for --render'
        manifest['renderers'] = {
            'dot': subprocess.run(['dot', '-V'], env=env, capture_output=True, check=True).stderr.decode(errors='replace').strip(),
            'ghostscript': subprocess.run([gs, '--version'], env=env, capture_output=True, check=True).stdout.decode().strip()}

        def validate_pdf(path):
            pdf = path.read_bytes()
            assert pdf.startswith(b'%PDF-1.4') and b'%%EOF' in pdf[-100:], path
            subprocess.run([gs, '-q', '-dSAFER', '-dNOPAUSE', '-dBATCH', '-sDEVICE=nullpage', '-f', str(path)],
                           env=env, capture_output=True, check=True, timeout=90)

        invoke('render', 'qpreroot', ['-g', 'graph', '-o', 'render.graph', '-d', 'render.dot'])
        save_file('render.dot')
        save_file('render.graph')
        save_file('render.pdf')
        validate_pdf(work / 'render.pdf')
        assert not (work / 'render.ps').exists()
        if os.name == 'nt':
            directory = work / 'render & graph files'
            directory.mkdir()
            invoke('render-spaces', 'qpreroot', ['-g', 'graph', '-d', 'render & graph files/graph path.dot'])
            validate_pdf(work / 'graph path.pdf')
            assert not (directory / 'graph path.ps').exists()
    (output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')


def compare(left, right):
    a, b = [json.loads((directory / 'manifest.json').read_text()) for directory in (left, right)]
    differences = []
    assert a['render'] == b['render'], 'run both platforms with the same --render setting'
    windows_only = {'invalid-crc', 'invalid-truncated', 'invalid-plain', 'invalid-empty', 'gzip-spaces', 'render-spaces'}
    expected = {'prepare-packed', 'prepare-transpose'} | {
        f'{prefix}-{kind}' for prefix in ('gzip', 'convert') for kind in ('text', 'packed', 'transpose', 'ancestry')}
    if a['render']:
        expected.add('render')
    assert set(a['cases']) - windows_only == set(b['cases']) - windows_only == expected, 'missing test cases'
    assert set(a['files']) == set(b['files']), 'missing generated files'
    shared = sorted(expected)
    for name in shared:
        assert a['cases'][name]['returncode'] == b['cases'][name]['returncode'] == 0
        for stream in ('stdout', 'stderr'):
            x, y = [normalized((directory / f'{name}.{stream}').read_bytes(), manifest['binary_dir'])
                    for directory, manifest in ((left, a), (right, b))]
            if x != y:
                import difflib
                differences.extend(difflib.unified_diff(x.splitlines(True), y.splitlines(True), fromfile=f'linux/{name}.{stream}', tofile=f'windows/{name}.{stream}'))
    files = sorted(a['files'].keys() | b['files'].keys())
    for name in files:
        # Rendering tools/fonts, timestamps and PDF metadata differ by OS/version.
        # Scientific data, graph structure and the DOT source are still exact.
        if name.endswith('.pdf'):
            continue
        if a['files'].get(name) != b['files'].get(name):
            differences.append(f'{name}: generated bytes differ\n')
    result = {'shared_cases': shared, 'exact_files': [name for name in files if not name.endswith('.pdf')],
              'differences': differences, 'gzip_results_identical': a['gzip_results_identical'] and b['gzip_results_identical']}
    (right / 'comparison.json').write_text(json.dumps(result, indent=2) + '\n')
    (right / 'comparison.diff').write_text(''.join(differences))
    print(json.dumps(result, indent=2))
    return bool(differences or not result['gzip_results_identical'])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bin', type=Path)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--render', action='store_true')
    parser.add_argument('--compare', nargs=2, type=Path)
    args = parser.parse_args()
    if args.compare:
        sys.exit(compare(*[p.resolve() for p in args.compare]))
    if not args.bin or not args.output:
        parser.error('use --bin and --output, or --compare')
    run(args.bin.resolve(), args.output.resolve(), args.render)
