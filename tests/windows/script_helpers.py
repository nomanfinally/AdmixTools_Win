"""Exercise installed Python conversion/extraction/merge/hash helpers on each OS.

Compare generated bytes with --compare LINUX WINDOWS. No external Python packages.
"""
import argparse
import contextlib
import errno
import hashlib
import json
import os
from pathlib import Path
import shutil
import sys
import tempfile
from unittest.mock import patch

import parity


def run(binary_dir, scripts, output):
    output.mkdir(parents=True, exist_ok=False)
    work = output / 'working directory with spaces'
    parity.fixtures(work)
    os.chdir(work)
    sys.path.insert(0, str(scripts))
    from convertf import convertf
    from extract_individuals import extract_multiple_individuals
    from merge_transpose import merge_geno_snp_ind
    from hash_checks import hash_checks
    temporary = work / 'temporary files with spaces'
    temporary.mkdir()
    tempfile.tempdir = str(temporary)
    os.environ.update(OPENBLAS_NUM_THREADS='1', OMP_NUM_THREADS='1', OPENBLAS_CORETYPE='NEHALEM')
    convertf(binary_dir, 'input', 'helper-transpose', 'transpose_packed')
    hash_checks('helper-transpose.geno', 'helper-transpose.ind', 'helper-transpose.snp')
    prefixes = ['helper-transpose', 'left-subset', 'right-subset', 'helper-merged']
    geno_single, merge_transpose = binary_dir / 'geno_single', binary_dir / 'merge_transpose'
    # Exercise Windows' denied-symlink fallback even on a Developer Mode machine.
    error = OSError(errno.EPERM, 'test: symlink privilege not held')
    error.winerror = 1314
    guard = patch.object(Path, 'symlink_to', side_effect=error) if os.name == 'nt' else contextlib.nullcontext()
    with guard:
        extract_multiple_individuals('helper-transpose', 'left-subset', ['Out0', 'A0'], geno_single, merge_transpose)
        extract_multiple_individuals('helper-transpose', 'right-subset', ['Out1', 'X0'], geno_single, merge_transpose)
    merge_geno_snp_ind(merge_transpose, ['left-subset', 'right-subset'], 'helper-merged')
    for prefix in prefixes:
        hash_checks(f'{prefix}.geno', f'{prefix}.ind', f'{prefix}.snp')
    # Upstream convertf may align fields; exact bytes are compared across OSes.
    rows = [line.split() for line in (work / 'helper-merged.ind').read_text().splitlines()]
    assert rows == [['Out0', 'U', 'Out'], ['A0', 'U', 'A'], ['Out1', 'U', 'Out'], ['X0', 'U', 'X']]
    files = {}
    for prefix in prefixes:
        for suffix in ('geno', 'ind', 'snp'):
            name = f'{prefix}.{suffix}'
            data = (work / name).read_bytes()
            shutil.copyfile(work / name, output / name)
            files[name] = hashlib.sha256(data).hexdigest()
            if suffix in ('ind', 'snp'):
                assert b'\r' not in data, name
    if os.name == 'nt':
        assert not (work / 'left-subset.snp').is_symlink()
        path = work / 'input & output paths'
        path.mkdir()
        prefix = path / 'sample file'
        for suffix in ('geno', 'ind', 'snp'):
            shutil.copyfile(work / f'input.{suffix}', f'{prefix}.{suffix}')
        convertf(binary_dir, prefix, path / 'result file', 'transpose_packed')
        for suffix in ('geno', 'ind', 'snp'):
            assert (path / f'result file.{suffix}').read_bytes() == (work / f'helper-transpose.{suffix}').read_bytes()
    assert not list(temporary.iterdir()), 'temporary helper directories were not removed'
    (output / 'manifest.json').write_text(json.dumps({'platform': sys.platform, 'files': files}, indent=2) + '\n')
    print(f'PASS: {len(files)} generated files; hashes, ordering and cleanup checked', flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bin', type=Path)
    parser.add_argument('--scripts', type=Path)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--compare', nargs=2, type=Path)
    args = parser.parse_args()
    if args.compare:
        a, b = [json.loads((p / 'manifest.json').read_text()) for p in args.compare]
        assert len(a['files']) == len(b['files']) == 12
        assert a['files'] == b['files'], 'generated helper files differ'
        print('PASS: all 12 generated helper files match byte-for-byte')
    else:
        if not args.bin or not args.scripts or not args.output:
            parser.error('use --bin, --scripts and --output, or --compare')
        run(args.bin.resolve(), args.scripts.resolve(), args.output.resolve())
